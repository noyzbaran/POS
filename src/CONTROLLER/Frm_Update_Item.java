    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       if (g_m.areEmptyFields(new JTextField[]{txtbarcode, txtproductName, txtdescription, txtOrigPrice, txtSKU,  (JTextField) txtSKU, (JTextField) txtPack, (JTextField) txtCriticalLevel})
                || g_m.areEmptyFields(new JTextField[]{txtbarcode, txtproductName, txtdescription, txtOrigPrice,  txtSKU}) || g_m.areEmptyFields(new JComboBox[]{cmbCategory, cmbSold})) {

            g_m.Error_Message("Input Error", "Empty Fields detected!");
        } else {
            
            if (JOptionPane.showConfirmDialog(null, "Are you sure you want to save the inputed data?", "Action Confirmation", JOptionPane.YES_NO_OPTION) == 0) {
                 d_m.ExeStatement("update tbl_product set product_name = '" + txtproductName.getText() + "',description = '" + txtdescription.getText() + "',sold_type = '" + cmbSold.getSelectedItem() + "'  ,unit_Price = '" + g_m.returnDouble(txtOrigPrice.getText()) + "',MarkupRetailPrice = '" + g_m.returnDouble(txtSKU.getText()) + "',markUpWholeSalePrice = '" + g_m.returnDouble(txtPack.getText()) + "',cat_id = (select category_id from tbl_prod_category where category = '" + cmbCategory.getSelectedItem() + "'),"
                         + "WholeSaleQuantity = '"+txtPack1.getText()+"',critical_level = '"+txtCriticalLevel.getText()+"',barcode = '" + txtbarcode.getText() + "' where barcode = '" + barcodeVal + "'  ", "Success! Item info is updated!");
                //g_m.Message("Success! New Item has inserted to the database");
                g_m.ClearFields(new JTextField[]{txtbarcode, txtproductName, txtdescription, txtOrigPrice,  (JTextField) txtSKU, (JTextField) txtPack, (JTextField) txtCriticalLevel});
                g_m.ClearCombo(new JComboBox[]{cmbCategory, cmbSold});
                dispose();
                d_m.FillTable(Frm_Dashboard.tbl_inventory,"select * from view_rough_inventory_summary");
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

