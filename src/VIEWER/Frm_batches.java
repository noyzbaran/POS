            d_m.ExeStatement("update tbl_stockin set expiration_date = '" + formatDate.format(date.getDate()) + "' where SKU = '" + tbl_inventory.getValueAt(tbl_inventory.getSelectedRow(), 0) + "' && barcode = '" + tbl_inventory.getValueAt(tbl_inventory.getSelectedRow(), 1) + "' ", "Success! Expiration of selected item is altered");
