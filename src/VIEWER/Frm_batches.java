    void displayInventory(String barcode) {
        try {
            d_m.FillTable(tbl_inventory, "Select SKU,item.barcode,item.product_Name,Quantity_piece,Quantity_pack,(Quantity_piece*Quantity_pack) as `Total Stockin`, '' as `StockOut`,\n"
                    + "Date_stored,expiration_date\n"
                    + "from tbl_stockin stock\n"
                    + "join tbl_product item on item.barcode = stock.barcode where item.barcode = '" + barcode + "'");

            Double totalOut = Double.valueOf(d_m.returnValue("select stockout from view_rough_stockout where barcode = '" + barcode + "' ", "stockout"));
            System.out.println(totalOut);
            int row = 0;
            Double par = 0.0;
            while (totalOut > 0) {
                //for(int i = 0;i < row;i++){
                Double val1 = Double.valueOf(tbl_inventory.getValueAt(row, 5).toString());
                totalOut -= val1;

                if (totalOut >= 0) {
                    tbl_inventory.setValueAt(tbl_inventory.getValueAt(row, 5), row, 6);
                    par = totalOut;
                    row++;
                } else {
                    tbl_inventory.setValueAt(par, row, 6);
                }
                System.out.println(totalOut);

            }
        } catch (Exception e) {
            System.out.println(e);
        }

    }

